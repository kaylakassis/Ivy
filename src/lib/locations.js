// One readable line for a stored answer, or null when unanswered.
export function locationLabel(state, country) {
  if (state && US_STATE_NAME[state]) return `${US_STATE_NAME[state]}, ${US_COUNTRY}`;
  if (country) return country;
  return null;
}
